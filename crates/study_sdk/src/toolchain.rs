//! Phase L Controlled Toolchain Policy, Reproducible Artifact Cache Keys, and
//! Deterministic Offline Preview Fixtures.
//!
//! Defines the pinned sandbox target (`wasm32-unknown-unknown`), explicit dependency allowlist,
//! upgrade-safe cache invalidation keys, and deterministic offline market fixtures so
//! authors can test studies without opening provider sessions or inventing a second
//! market-data owner.

use crate::sandbox::{STUDY_SANDBOX_ABI_VERSION, StudySandboxColumnarBars};
use crate::{AggressorSide, STUDY_SDK_COMPATIBILITY_EPOCH, StudyTradeSample};

/// Version of the controlled toolchain policy schema.
pub const STUDY_TOOLCHAIN_POLICY_VERSION: u32 = 1;
/// Required zero-authority portable WebAssembly target triple for sandboxed user studies.
pub const STUDY_SANDBOX_TARGET_TRIPLE: &str = "wasm32-unknown-unknown";
/// Maximum bars generated by one offline preview fixture.
pub const MAXIMUM_PREVIEW_FIXTURE_BARS: usize = 2_048;

/// Static allowlist of crate dependencies permitted inside user-authored sandboxed studies.
pub const ALLOWED_USER_STUDY_CRATES: &[&str] = &["aeris_study_sdk"];

/// Validates whether a requested dependency crate name is permitted by the controlled toolchain.
#[must_use]
pub fn is_allowed_study_dependency(crate_name: &str) -> bool {
    ALLOWED_USER_STUDY_CRATES.contains(&crate_name)
}

/// Deterministic, upgrade-safe cache key for one compiled sandboxed study artifact.
///
/// Any change in source, SDK compatibility epoch, sandbox ABI version, compiler identity,
/// target triple, or dependency lock digest produces a distinct cache key so incompatible
/// cached artifacts are never reused across upgrades while source remains recoverable.
#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct StudyArtifactCacheKey {
    pub policy_version: u32,
    pub sdk_compatibility_epoch: u32,
    pub sandbox_abi_version: u32,
    pub toolchain_identity: String,
    pub target_triple: String,
    pub source_sha256: String,
    pub lockfile_sha256: String,
}

impl StudyArtifactCacheKey {
    /// Builds a cache key pinned to the host's current policy, SDK epoch, ABI version,
    /// and target triple.
    #[must_use]
    pub fn for_host(
        toolchain_identity: impl Into<String>,
        source_sha256: impl Into<String>,
        lockfile_sha256: impl Into<String>,
    ) -> Self {
        Self {
            policy_version: STUDY_TOOLCHAIN_POLICY_VERSION,
            sdk_compatibility_epoch: STUDY_SDK_COMPATIBILITY_EPOCH,
            sandbox_abi_version: STUDY_SANDBOX_ABI_VERSION,
            toolchain_identity: toolchain_identity.into(),
            target_triple: STUDY_SANDBOX_TARGET_TRIPLE.to_string(),
            source_sha256: source_sha256.into(),
            lockfile_sha256: lockfile_sha256.into(),
        }
    }

    /// Returns whether this cache key is compatible with the currently running Aeris host.
    #[must_use]
    pub fn is_compatible_with_host(&self, host_toolchain_identity: &str) -> bool {
        self.policy_version == STUDY_TOOLCHAIN_POLICY_VERSION
            && self.sdk_compatibility_epoch == STUDY_SDK_COMPATIBILITY_EPOCH
            && self.sandbox_abi_version == STUDY_SANDBOX_ABI_VERSION
            && self.target_triple == STUDY_SANDBOX_TARGET_TRIPLE
            && self.toolchain_identity == host_toolchain_identity
    }

    /// Returns a deterministic filesystem-safe cache filename prefix.
    #[must_use]
    pub fn cache_slug(&self) -> String {
        let src_prefix = self.source_sha256.get(..12).unwrap_or(&self.source_sha256);
        let lock_prefix = self
            .lockfile_sha256
            .get(..8)
            .unwrap_or(&self.lockfile_sha256);
        format!(
            "p{}_sdk{}_abi{}_{src_prefix}_{lock_prefix}",
            self.policy_version, self.sdk_compatibility_epoch, self.sandbox_abi_version
        )
    }
}

/// Reproducible metadata receipt recorded alongside one compiled user-study artifact.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct StudyBuildArtifactMetadata {
    pub cache_key: StudyArtifactCacheKey,
    pub identifier: String,
    pub implementation_revision: u32,
    pub artifact_sha256: String,
    pub artifact_bytes: usize,
}

impl StudyBuildArtifactMetadata {
    /// Checks structural validity of the recorded digests and compatibility fields.
    #[must_use]
    pub fn is_valid(&self) -> bool {
        let valid_sha =
            |value: &str| value.len() == 64 && value.bytes().all(|b| b.is_ascii_hexdigit());
        self.implementation_revision > 0
            && !self.identifier.is_empty()
            && !self.identifier.starts_with("builtin.")
            && self.artifact_bytes > 0
            && valid_sha(&self.artifact_sha256)
            && valid_sha(&self.cache_key.source_sha256)
            && valid_sha(&self.cache_key.lockfile_sha256)
    }
}

/// Availability status of the optional Aeris Study Development Pack toolchain.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum StudyDevPackStatus {
    /// Local compiler and required `wasm32-wasip2` target are installed and ready.
    Ready {
        rustc_version: String,
        target_triple: String,
    },
    /// Local compiler exists, but the required WebAssembly sandbox target is missing.
    MissingSandboxTarget {
        rustc_version: String,
        required_target: String,
    },
    /// No local Rust toolchain / Development Pack was detected.
    Unavailable,
}

/// Deterministic offline market fixture presets for testing studies without provider sessions.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum PreviewFixturePreset {
    /// Steady upward drift with realistic OHLC wicks and positive buy-volume skew.
    Uptrend,
    /// Mean-reverting oscillating channel for testing oscillators and band fills.
    RangeBound,
    /// Quiet consolidation followed by a sharp breakout spike for testing alerts and ATR.
    VolatilitySpike,
    /// Series containing an explicit multi-bar time gap for testing hard-gap handling.
    GapRecovery,
}

/// Deterministic offline market dataset for author tests and Study Editor previews.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct StudyPreviewFixture {
    pub preset: PreviewFixturePreset,
    pub bars: StudySandboxColumnarBars,
    pub trades: Vec<StudyTradeSample>,
}

impl StudyPreviewFixture {
    /// Generates a deterministic, repeatable fixed-point OHLCV + trade fixture clamped to
    /// `1..=MAXIMUM_PREVIEW_FIXTURE_BARS` bars (price scale 2, quantity scale 0).
    #[must_use]
    pub fn generate(preset: PreviewFixturePreset, bar_count: usize, interval_secs: i64) -> Self {
        let count = bar_count.clamp(1, MAXIMUM_PREVIEW_FIXTURE_BARS);
        let step_ns = interval_secs.max(1).saturating_mul(1_000_000_000);
        let base_ts: i64 = 1_700_000_000_000_000_000;

        let mut timestamps_unix_nanos = Vec::with_capacity(count);
        let mut open = Vec::with_capacity(count);
        let mut high = Vec::with_capacity(count);
        let mut low = Vec::with_capacity(count);
        let mut close = Vec::with_capacity(count);
        let mut volume = Vec::with_capacity(count);
        let mut trades = Vec::with_capacity(count * 2);

        let mut prev_close: i64 = 10_000; // 100.00 at scale 2
        for idx in 0..count {
            let i = i64::try_from(idx).unwrap_or(i64::MAX);
            let gap_offset = if preset == PreviewFixturePreset::GapRecovery && idx >= count / 2 {
                step_ns.saturating_mul(5)
            } else {
                0
            };
            let ts = base_ts
                .saturating_add(i.saturating_mul(step_ns))
                .saturating_add(gap_offset);
            let delta = match preset {
                PreviewFixturePreset::Uptrend => 15 + ((i % 5) - 2) * 5,
                PreviewFixturePreset::RangeBound => {
                    if (i / 6) % 2 == 0 {
                        20
                    } else {
                        -20
                    }
                }
                PreviewFixturePreset::VolatilitySpike => {
                    if idx >= (count * 2) / 3 && idx < (count * 2) / 3 + 5 {
                        120
                    } else {
                        ((i % 3) - 1) * 5
                    }
                }
                PreviewFixturePreset::GapRecovery => {
                    if idx == count / 2 {
                        180
                    } else {
                        10
                    }
                }
            };
            let bar_open = prev_close;
            let bar_close = (bar_open + delta).max(100);
            let bar_high = bar_open.max(bar_close) + 12;
            let bar_low = (bar_open.min(bar_close) - 12).max(50);
            let bar_vol = 100 + (i % 7) * 25;

            timestamps_unix_nanos.push(ts);
            open.push(bar_open);
            high.push(bar_high);
            low.push(bar_low);
            close.push(bar_close);
            volume.push(bar_vol);

            trades.push(StudyTradeSample {
                observed_unix_nanos: ts.saturating_add(step_ns / 4),
                price: bar_open,
                quantity: bar_vol / 2,
                aggressor: if delta >= 0 {
                    AggressorSide::Buy
                } else {
                    AggressorSide::Sell
                },
            });
            trades.push(StudyTradeSample {
                observed_unix_nanos: ts.saturating_add((step_ns * 3) / 4),
                price: bar_close,
                quantity: bar_vol - (bar_vol / 2),
                aggressor: if delta >= 0 {
                    AggressorSide::Buy
                } else {
                    AggressorSide::Sell
                },
            });
            prev_close = bar_close;
        }

        Self {
            preset,
            bars: StudySandboxColumnarBars {
                price_scale: 2,
                quantity_scale: 0,
                timestamps_unix_nanos,
                open,
                high,
                low,
                close,
                volume,
            },
            trades,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cache_key_invalidates_on_epoch_abi_or_toolchain_upgrade() {
        let src = "a".repeat(64);
        let lock = "b".repeat(64);
        let key = StudyArtifactCacheKey::for_host("rustc 1.99.0", src.clone(), lock.clone());
        assert!(key.is_compatible_with_host("rustc 1.99.0"));
        assert!(!key.is_compatible_with_host("rustc 1.100.0"));
        assert!(key.cache_slug().starts_with("p1_sdk1_abi1_"));

        let mut stale_sdk = key.clone();
        stale_sdk.sdk_compatibility_epoch += 1;
        assert!(!stale_sdk.is_compatible_with_host("rustc 1.99.0"));

        let meta = StudyBuildArtifactMetadata {
            cache_key: key,
            identifier: "user.ksr6".to_string(),
            implementation_revision: 1,
            artifact_sha256: "c".repeat(64),
            artifact_bytes: 1024,
        };
        assert!(meta.is_valid());
    }

    #[test]
    fn dependency_allowlist_permits_only_study_sdk() {
        assert!(is_allowed_study_dependency("aeris_study_sdk"));
        assert!(!is_allowed_study_dependency("reqwest"));
        assert!(!is_allowed_study_dependency("libc"));
    }

    #[test]
    fn offline_preview_fixtures_are_deterministic_consistent_and_bounded() {
        for preset in [
            PreviewFixturePreset::Uptrend,
            PreviewFixturePreset::RangeBound,
            PreviewFixturePreset::VolatilitySpike,
            PreviewFixturePreset::GapRecovery,
        ] {
            let a = StudyPreviewFixture::generate(preset, 60, 60);
            let b = StudyPreviewFixture::generate(preset, 60, 60);
            assert_eq!(a, b);
            assert!(a.bars.is_consistent());
            assert_eq!(a.bars.len(), 60);
            assert_eq!(a.trades.len(), 120);
        }
    }
}
